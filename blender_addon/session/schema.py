# IDLE → no draft, no recent failure
# EXPLORING → reading scene/GN
# DRAFTING → drafting an unexecuted script
# PENDING_USER_EXECUTION → draft newer than what was last executed
# REPAIRING → last execution failed, draft needs a fix
# RESOLVED → last execution succeeded for current revision
