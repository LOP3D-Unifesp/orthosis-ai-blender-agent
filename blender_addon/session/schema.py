@dataclass
class Session:
    identity: Identity = field(default_factory=Identity)
    focus: Focus = field(default_factory=Focus)
    baseline_workspace: BaselineWorkspace = field(default_factory=BaselineWorkspace)
    history: History = field(default_factory=History)
    execution_state: ExecutionState = field(default_factory=ExecutionState)
    ui_state: UIState = field(default_factory=UIState)
    operational_state: OperationalState = field(default_factory=OperationalState)
    lifecycle: Lifecycle = field(default_factory=Lifecycle)

    # ---- invariants ------------------------------------------------------

    def update_focus(
        self,
        *,
        blend_path: str | None = None,
        object_name: str | None = None,
        modifier_name: str | None = None,
        tree_name: str | None = None,
    ) -> bool:
        """Update focus coordinates and enforce invariants.

        Returns ``True`` if the focus actually changed.
        """
        new_blend_path = self.focus.blend_path if blend_path is None else str(blend_path)
        new_object = self.focus.object_name if object_name is None else (str(object_name) if object_name else None)
        new_modifier = self.focus.modifier_name if modifier_name is None else (str(modifier_name) if modifier_name else None)
        new_tree = self.focus.tree_name if tree_name is None else (str(tree_name) if tree_name else None)
        new_signature = compute_focus_signature(new_blend_path, new_object, new_modifier, new_tree)
        if new_signature == self.focus.focus_signature:
            return False
        self.focus = Focus(
            blend_path=new_blend_path,
            object_name=new_object,
            modifier_name=new_modifier,
            tree_name=new_tree,
            focus_signature=new_signature,
            focus_changed_at=utc_now_iso(),
        )
        # The baseline was built against the old focus; mark it stale.
        self.baseline_workspace.mark_stale()
        return True

    def mark_baseline_stale(self) -> None:
        self.baseline_workspace.mark_stale()

    def touch(self) -> None:
        self.identity.touch()

    # ---- serialisation ---------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.identity.schema_version,
            "identity": self.identity.to_dict(),
            "focus": self.focus.to_dict(),
            "baseline_workspace": self.baseline_workspace.to_dict(),
            "history": self.history.to_dict(),
            "execution_state": self.execution_state.to_dict(),
            "ui_state": self.ui_state.to_dict(),
            "operational_state": self.operational_state.to_dict(),
            "lifecycle": self.lifecycle.to_dict(),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any] | None) -> "Session":
        data = data or {}
        identity = Identity.from_dict(data.get("identity"))
        # Always normalise the schema_version on the way in.
        identity.schema_version = SCHEMA_VERSION
        return cls(
            identity=identity,
            focus=Focus.from_dict(data.get("focus")),
            baseline_workspace=BaselineWorkspace.from_dict(data.get("baseline_workspace")),
            history=History.from_dict(data.get("history")),
            execution_state=ExecutionState.from_dict(data.get("execution_state")),
            ui_state=UIState.from_dict(data.get("ui_state")),
            operational_state=OperationalState.from_dict(data.get("operational_state")),
            lifecycle=Lifecycle.from_dict(data.get("lifecycle")),
        )

    @classmethod
    def new(cls, blend_path: str = "") -> "Session":
        """Construct an empty Session bound to ``blend_path``."""
        focus = Focus(blend_path=blend_path or "")
        return cls(focus=focus)


