            subgraph_index=_as_dict(data.get("subgraph_index")),
            recipe_associations=_as_list_of_dicts(data.get("recipe_associations")),
            known_parameters=_as_dict(data.get("known_parameters")),
            open_questions=[str(item) for item in (data.get("open_questions") or []) if str(item).strip()],
