@dataclass
class History:
    max_messages: int = DEFAULT_MAX_HISTORY_MESSAGES
    messages: list[HistoryMessage] = field(default_factory=list)
    older_summary: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "max_messages": self.max_messages,
            "messages": [msg.to_dict() for msg in self.messages],
            "older_summary": self.older_summary,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any] | None) -> "History":
        data = data or {}
        raw_messages = data.get("messages") or []
        messages: list[HistoryMessage] = []
        for item in raw_messages:
            if isinstance(item, dict):
                messages.append(HistoryMessage.from_dict(item))
        older_summary = data.get("older_summary")
        return cls(
            max_messages=int(data.get("max_messages") or DEFAULT_MAX_HISTORY_MESSAGES),
            messages=messages,
            older_summary=str(older_summary) if older_summary else None,
        )


