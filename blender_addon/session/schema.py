def utc_now_iso() -> str:
    """Return a stable, second-precision UTC ISO-8601 timestamp."""
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def new_session_id() -> str:
    """Generate a new opaque session id."""
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    return f"sess-{ts}-{uuid4().hex[:8]}"


def new_continuity_token() -> str:
    """Generate an opaque continuity token used to reattach across restarts."""
    return f"cont-{uuid4().hex[:12]}"


def compute_focus_signature(
    blend_path: str | None,
    object_name: str | None,
    modifier_name: str | None,
    tree_name: str | None,
) -> str:
    """Compute a stable signature for the current focus.

    The signature is a short hex digest of the four focus coordinates joined
    by ``|``. ``None`` and empty strings are normalised so that two equivalent
    focuses always produce the same signature.
    """
    parts = [
        str(blend_path or ""),
        str(object_name or ""),
        str(modifier_name or ""),
        str(tree_name or ""),
    ]
    raw = "|".join(parts).encode("utf-8")
    return hashlib.sha1(raw).hexdigest()[:16]


