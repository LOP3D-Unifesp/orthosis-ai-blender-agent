"""Structured Session schema for Phase 1 of REFATOR_PLAN.md.

This module defines the structured domain blocks that replace the legacy flat
session dict in later phases:

    Session
    ├── identity
    ├── focus
    ├── baseline_workspace
    ├── history
    ├── execution_state
    ├── ui_state
    ├── operational_state
    └── lifecycle

The dataclasses here are the *single source of truth* for the v1 schema shape.
``SessionV1Store`` (in ``store.py``) handles persistence and legacy migration.

Invariants enforced at this layer:

* ``identity.schema_version`` is always ``"1.0"`` after construction.
* There are no approval tokens, plan tokens, or ``presented_plan_*`` fields
  anywhere in this schema (removed through the Onda 1 series).
* Updating ``focus`` marks the baseline stale.

These invariants live on the dataclasses themselves so that any future
consumer (the runtime, the router, tests) cannot skip them by accident.
"""

from __future__ import annotations

