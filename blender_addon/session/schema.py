@dataclass
class Lifecycle:
    continuity_token: str = field(default_factory=new_continuity_token)
    prior_session_ids: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def remember_prior_session(self, session_id: str) -> None:
        sid = str(session_id or "").strip()
        if not sid:
            return
        if sid in self.prior_session_ids:
            return
        self.prior_session_ids.append(sid)
        if len(self.prior_session_ids) > DEFAULT_MAX_PRIOR_SESSION_IDS:
            del self.prior_session_ids[:-DEFAULT_MAX_PRIOR_SESSION_IDS]

    def add_note(self, note: str) -> None:
        text = str(note or "").strip()
        if not text:
            return
        self.notes.append(text)
        if len(self.notes) > DEFAULT_MAX_LIFECYCLE_NOTES:
            del self.notes[:-DEFAULT_MAX_LIFECYCLE_NOTES]

    def to_dict(self) -> dict[str, Any]:
        return {
            "continuity_token": self.continuity_token,
            "prior_session_ids": list(self.prior_session_ids),
            "notes": list(self.notes),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any] | None) -> "Lifecycle":
        data = data or {}
        return cls(
            continuity_token=str(data.get("continuity_token") or new_continuity_token()),
            prior_session_ids=[str(item) for item in (data.get("prior_session_ids") or []) if str(item).strip()],
            notes=[str(item) for item in (data.get("notes") or []) if str(item).strip()],
        )


